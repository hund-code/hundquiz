create table if not exists public.quiz_scores (
  id bigint generated by default as identity primary key,
  nickname text not null check (
    nickname = btrim(nickname)
    and char_length(nickname) between 2 and 16
  ),
  score integer not null check (score >= 0),
  created_at timestamptz not null default now()
);

alter table public.quiz_scores
  drop constraint if exists quiz_scores_score_check;
alter table public.quiz_scores
  add constraint quiz_scores_score_check check (score >= 0);

create unique index if not exists quiz_scores_nickname_unique_idx
  on public.quiz_scores (lower(btrim(nickname)));

create index if not exists quiz_scores_rank_idx
  on public.quiz_scores (score desc, created_at asc);

alter table public.quiz_scores enable row level security;

drop policy if exists "Public can read quiz scores" on public.quiz_scores;
create policy "Public can read quiz scores"
  on public.quiz_scores
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can submit quiz scores" on public.quiz_scores;
drop policy if exists "Authenticated users can submit their own scores" on public.quiz_scores;
create policy "Public can submit quiz scores"
  on public.quiz_scores
  for insert
  to anon, authenticated
  with check (
    nickname = btrim(nickname)
    and char_length(nickname) between 2 and 16
    and score >= 0
  );

revoke update, delete on public.quiz_scores from anon, authenticated;
grant select, insert on public.quiz_scores to anon, authenticated;
grant usage, select on sequence public.quiz_scores_id_seq to anon, authenticated;
