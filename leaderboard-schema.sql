create table if not exists public.quiz_scores (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  nickname text not null check (
    nickname = btrim(nickname)
    and char_length(nickname) between 2 and 16
  ),
  score integer not null check (score between 0 and 100),
  created_at timestamptz not null default now()
);

alter table public.quiz_scores
  add column if not exists user_id uuid references auth.users(id) on delete cascade;

create index if not exists quiz_scores_rank_idx
  on public.quiz_scores (score desc, created_at asc);

alter table public.quiz_scores enable row level security;

drop policy if exists "Public can read quiz scores" on public.quiz_scores;
create policy "Public can read quiz scores"
  on public.quiz_scores
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can submit quiz scores" on public.quiz_scores;
drop policy if exists "Authenticated users can submit their own scores" on public.quiz_scores;
create policy "Authenticated users can submit their own scores"
  on public.quiz_scores
  for insert
  to authenticated
  with check (
    auth.uid() = user_id
    and
    nickname = btrim(nickname)
    and char_length(nickname) between 2 and 16
    and score between 0 and 100
  );

revoke insert, update, delete on public.quiz_scores from anon;
grant select on public.quiz_scores to anon, authenticated;
grant insert on public.quiz_scores to authenticated;
grant usage, select on sequence public.quiz_scores_id_seq to authenticated;